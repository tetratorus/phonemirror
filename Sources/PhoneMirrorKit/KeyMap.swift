import CoreGraphics

/// Maps Mac virtual key codes to USB HID keyboard usages (page 7), so the phone
/// receives what a hardware keyboard would send. Keys are positional: the phone
/// applies its own hardware-keyboard layout.
public enum KeyMap {
  public static let control: UInt8 = 0xe0
  public static let shift: UInt8 = 0xe1
  public static let option: UInt8 = 0xe2
  public static let command: UInt8 = 0xe3

  static let usages: [UInt16: UInt8] = [
    0x00: 0x04, 0x01: 0x16, 0x02: 0x07, 0x03: 0x09, 0x04: 0x0b, 0x05: 0x0a, 0x06: 0x1d, 0x07: 0x1b,
    0x08: 0x06, 0x09: 0x19, 0x0a: 0x64, 0x0b: 0x05, 0x0c: 0x14, 0x0d: 0x1a, 0x0e: 0x08, 0x0f: 0x15,
    0x10: 0x1c, 0x11: 0x17, 0x12: 0x1e, 0x13: 0x1f, 0x14: 0x20, 0x15: 0x21, 0x16: 0x23, 0x17: 0x22,
    0x18: 0x2e, 0x19: 0x26, 0x1a: 0x24, 0x1b: 0x2d, 0x1c: 0x25, 0x1d: 0x27, 0x1e: 0x30, 0x1f: 0x12,
    0x20: 0x18, 0x21: 0x2f, 0x22: 0x0c, 0x23: 0x13, 0x24: 0x28, 0x25: 0x0f, 0x26: 0x0d, 0x27: 0x34,
    0x28: 0x0e, 0x29: 0x33, 0x2a: 0x31, 0x2b: 0x36, 0x2c: 0x38, 0x2d: 0x11, 0x2e: 0x10, 0x2f: 0x37,
    0x30: 0x2b, 0x31: 0x2c, 0x32: 0x35, 0x33: 0x2a, 0x35: 0x29,
    // Keypad
    0x41: 0x63, 0x43: 0x55, 0x45: 0x57, 0x47: 0x53, 0x4b: 0x54, 0x4c: 0x58, 0x4e: 0x56, 0x51: 0x67,
    0x52: 0x62, 0x53: 0x59, 0x54: 0x5a, 0x55: 0x5b, 0x56: 0x5c, 0x57: 0x5d, 0x58: 0x5e, 0x59: 0x5f,
    0x5b: 0x60, 0x5c: 0x61,
    // JIS
    0x5d: 0x89, 0x5e: 0x87, 0x5f: 0x85, 0x66: 0x91, 0x68: 0x90,
    // Function and navigation
    0x7a: 0x3a, 0x78: 0x3b, 0x63: 0x3c, 0x76: 0x3d, 0x60: 0x3e, 0x61: 0x3f, 0x62: 0x40, 0x64: 0x41,
    0x65: 0x42, 0x6d: 0x43, 0x67: 0x44, 0x6f: 0x45,
    0x73: 0x4a, 0x74: 0x4b, 0x75: 0x4c, 0x77: 0x4d, 0x79: 0x4e,
    0x7b: 0x50, 0x7c: 0x4f, 0x7d: 0x51, 0x7e: 0x52,
  ]

  /// The HID chord for a key press, modifiers first; nil for keys a phone keyboard lacks.
  public static func chord(keyCode: UInt16, flags: CGEventFlags) -> [UInt8]? {
    guard let usage = usages[keyCode] else { return nil }
    var chord: [UInt8] = []
    if flags.contains(.maskControl) { chord.append(control) }
    if flags.contains(.maskShift) { chord.append(shift) }
    if flags.contains(.maskAlternate) { chord.append(option) }
    if flags.contains(.maskCommand) { chord.append(command) }
    return chord + [usage]
  }
}
